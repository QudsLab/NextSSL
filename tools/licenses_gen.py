#!/usr/bin/env python3
"""Generate licenses/: one folder per algorithm with its upstream license files, plus licenses/README.md.

    python3 tools/licenses_gen.py           (re)write licenses/
    python3 tools/licenses_gen.py --check   exit 1 when licenses/ is out of date (CI guard)

Source of truth: docs/algo.generated.json (id, dir, SPDX id, upstream) and each algorithm's upstream/
folder. Files copied: the top-level license-like files of upstream/ (LICENSE*, LICENCE*, COPYING*, NOTICE*,
UNLICENSE*, COPYRIGHT*, AUTHORS*, PATENTS*) and ORIGIN.md, byte for byte. An algorithm without such a file
gets SOURCE.md naming the crate or upstream it comes from. Never edit licenses/ by hand.
"""
import json
import os
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'licenses')
PREFIXES = ('LICENSE', 'LICENCE', 'COPYING', 'NOTICE', 'UNLICENSE', 'COPYRIGHT', 'AUTHORS', 'PATENTS')


def norm(b):
    # Line endings follow the checkout (.gitattributes, core.autocrlf); compare without them.
    return b.replace(b'\r\n', b'\n')


def wanted(name):
    return name == 'ORIGIN.md' or name.upper().startswith(PREFIXES)


def build():
    """Returns {relative path under licenses/: bytes}."""
    with open(os.path.join(ROOT, 'docs', 'algo.generated.json'), encoding='utf-8') as f:
        algos = json.load(f)['algorithms']
    files = {}
    rows = []
    for a in sorted(algos, key=lambda x: x['id']):
        aid, up = a['id'], a.get('upstream', {})
        spdx = up.get('license') or 'NOASSERTION'
        src = os.path.join(ROOT, 'algos', a['dir'], 'upstream')
        names = []
        if os.path.isdir(src):
            for n in sorted(os.listdir(src)):
                p = os.path.join(src, n)
                if os.path.isfile(p) and wanted(n):
                    with open(p, 'rb') as f:
                        files[f'{aid}/{n}'] = norm(f.read())
                    names.append(n)
        if not any(n != 'ORIGIN.md' for n in names):
            origin = up.get('crate') and f"Rust crate `{up['crate']}` {up.get('version', '')} (crates.io)"
            origin = origin or up.get('url') or up.get('repo') or a.get('source', {}).get('label', 'see algos/' + a['dir'])
            files[f'{aid}/SOURCE.md'] = (
                f'# {aid}\n\nUpstream: {origin}\nLicense (algo.toml): {spdx}\n'
                f'No license file is bundled with this upstream copy; the SPDX id above is what algo.toml records.\n'
                f'Source in this repository: algos/{a["dir"]}/\n').encode()
            names.append('SOURCE.md')
        rows.append((aid, spdx, a.get('tier', ''), a['dir'], names))
    lines = [
        '# Third-party licenses', '',
        'Generated by tools/licenses_gen.py from docs/algo.generated.json and each algorithm\'s upstream/ folder;',
        'do not edit. Every algorithm keeps the license of its upstream authors; the files in `<id>/` are copied',
        'byte for byte. NextSSL\'s own code is under the repository LICENSE.', '',
        f'{len(rows)} algorithms.', '',
        '| algorithm | license (SPDX, algo.toml) | tier | source | files |',
        '|---|---|---|---|---|',
    ]
    for aid, spdx, tier, d, names in rows:
        lines.append(f'| [{aid}]({aid}/) | {spdx} | {tier} | `algos/{d}` | {", ".join(names)} |')
    files['README.md'] = ('\n'.join(lines) + '\n').encode()
    return files


def current():
    have = {}
    if os.path.isdir(OUT):
        for dp, _, fns in os.walk(OUT):
            for n in fns:
                p = os.path.join(dp, n)
                with open(p, 'rb') as f:
                    have[os.path.relpath(p, OUT).replace(os.sep, '/')] = norm(f.read())
    return have


def main():
    want = build()
    if '--check' in sys.argv:
        have = current()
        bad = sorted(k for k in set(want) | set(have) if want.get(k) != have.get(k))
        if bad:
            print(f'licenses/ is out of date ({len(bad)} files, e.g. {bad[:3]}): run python3 tools/licenses_gen.py')
            sys.exit(1)
        print(f'licenses/ is current ({len(want)} files)')
        return
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    for rel, data in want.items():
        p = os.path.join(OUT, *rel.split('/'))
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, 'wb') as f:
            f.write(data)
    print(f'wrote licenses/: {len(want)} files')


if __name__ == '__main__':
    main()
