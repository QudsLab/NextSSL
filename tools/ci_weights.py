#!/usr/bin/env python3
"""Write tools/ci_weights.tsv from one CI test report: build seconds per crate and seconds per test.

    python3 tools/ci_weights.py <test-report dir with cargo-timing.html and test-times.tsv>

tools/testrun.py uses the file to split the workspace into shards of equal expected time
(--shard K/N) and to start the longest tests first. Weights are relative: one platform's report
(linux-x64) is used for every platform. Crates missing from the file get the median weight, so a
new algorithm is never left out of a shard. Standard library only.
"""
import collections
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'tools', 'ci_weights.tsv')


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    rep = sys.argv[1]
    html = open(os.path.join(rep, 'cargo-timing.html'), encoding='utf-8').read()
    units = json.loads(re.search(r'const UNIT_DATA = (\[.*?\]);\s*\n', html, re.S).group(1))
    build = collections.Counter()
    for u in units:
        build[u['name']] += u['duration']
    tests = []
    with open(os.path.join(rep, 'test-times.tsv'), encoding='utf-8') as f:
        next(f)
        for line in f:
            secs, crate, test = line.rstrip('\n').split('\t')
            tests.append((crate, test, float(secs)))
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write('# Generated by tools/ci_weights.py from one CI test report; relative weights for\n')
        f.write('# tools/testrun.py --shard and test ordering. kind<TAB>crate<TAB>test<TAB>seconds\n')
        for crate in sorted(build):
            f.write(f'build\t{crate}\t-\t{build[crate]:.1f}\n')
        for crate, test, secs in sorted(tests):
            f.write(f'test\t{crate}\t{test}\t{secs:.2f}\n')
    print(f'wrote {os.path.relpath(OUT, ROOT)}: {len(build)} crates, {len(tests)} tests')


if __name__ == '__main__':
    main()
