/* Values from NIST API */
typedef unsigned char BitSequence;
typedef unsigned long long DataLength;
typedef enum {SUCCESS = 0,  FAIL = 1, BAD_HASHBITLEN = 2} HashReturn;

typedef struct {
  int hashbitlen;
  int numUnprocessed;        //Number of unprocessed bits
  BitSequence *unprocessed;  //Unprocessed data storage
  BitSequence *curr;         //Current result so far.
  DataLength datalen;        //Total length processed so far.

  //the following are used to generate the square-free sequence
  BitSequence *p[3];    //Pegs for the Towers of Hanoi.  Each array reads "up" 
                        //  one peg; the values are the sizes of the disks.
  BitSequence *top[3];  //Pointers to the tops of the stacks on each peg.
  BitSequence parity;   //Parity of the number of moves so far.  Used as a 
                        //  calculational aid for efficiency.
  BitSequence small;    //Peg on which the smallest disk is currently located.
                        //  Used as a calculational aid for efficiency.
  BitSequence count;    //The current value of the 5-bit counter.
  BitSequence move;     //The current move value (from+3*to), in the three 
                        //  high-order bits.

} hashState;

//state is where the initialized state gets returned
HashReturn Init(hashState *state, int hashbitlen);

//process as much data as you can, update state
HashReturn Update(hashState *state, const BitSequence *data, 
		  DataLength databitlen);

//perform final block processing, return result in hashval
HashReturn Final(hashState *state, BitSequence *hashval);

//all-at-once hash - should call above fns
HashReturn Hash(int hashbitlen, const BitSequence *data, 
		DataLength databitlen, BitSequence *hashval);




